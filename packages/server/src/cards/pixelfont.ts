/** Total columns `pixelTextPath` occupies, for right-aligning and measuring. */
export function pixelTextColumns(text: string): number {
  let columns = 0;
  for (const char of text.toUpperCase()) {
    const glyph = GLYPHS[char];
    if (glyph === undefined) continue;
    if (columns > 0) columns += 1;
    columns += glyph[0]?.length ?? 0;
  }
  return columns;
}

/** One-unit-per-pixel path for `text`; scale/position via SVG transform.
 * Characters without a glyph are dropped (the card only renders pinned
 * uppercase copy, digits, and amount punctuation). */
export function pixelTextPath(text: string): string {
  let d = "";
  let offset = 0;
  for (const char of text.toUpperCase()) {
    const glyph = GLYPHS[char];
    if (glyph === undefined) continue;
    if (offset > 0) offset += 1;
    for (let row = 0; row < glyph.length; row += 1) {
      const line = glyph[row] as string;
      for (let col = 0; col < line.length; col += 1) {
        if (line[col] !== "#") continue;
        d += `M${offset + col} ${row}h1v1h-1z`;
      }
    }
    offset += glyph[0]?.length ?? 0;
  }
  return d;
}
